const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { normalize } = require('../codigo/normalizar.js');
const root = path.resolve(__dirname, '..');
const leads = JSON.parse(fs.readFileSync(path.join(root, 'datos/leads.json'), 'utf8'));
const results = leads.map(normalize);
assert.equal(results.filter(r => r.valid).length, 3);
assert.equal(results.filter(r => r.eligible).length, 2);
assert.equal(results[0].data.email, 'ana@example.com');
assert.equal(normalize({...leads[0], consent: 'false'}).eligible, false);
assert.equal(normalize(null).valid, false);

function file(name) {return fs.readFileSync(path.join(root, 'codigo', name), 'utf8');}
const n8n = new Function('$input', file('n8n_normalizar.js'));
const nout = n8n({all: () => leads.map(json => ({json}))});
assert.equal(nout.filter(r => r.json.eligible).length, 2);
assert.deepEqual(nout[4].pairedItem, {item: 4});
const raw = n8n({all: () => [{json: {body: leads[0]}}]});
assert.equal(raw[0].json.data.lead_id, 'L001');
const zap = new Function('inputData', file('zapier_desde_campos.js'));
assert.equal(zap({...leads[0], consent: 'TRUE'}).eligible, true);
assert.equal(zap({...leads[0], consent: 'FALSE'}).eligible, false);
assert.throws(() => zap({...leads[0], consent: 'sí'}));
const ap = new Function('$input', file('n8n_aprobaciones.js'));
const row = {estado: 'APROBADO', revision: 1, aprobada_revision: 1, aprobado_por: 'revisor-demo', payload_json: JSON.stringify(leads[0])};
assert.equal(ap({all: () => [{json: row}]})[0].json.approval_valid, true);
assert.equal(ap({all: () => [{json: {...row, revision: 2}}]})[0].json.approval_valid, false);
const report = new Function('$input', file('n8n_reporte.js'));
const totals = report({all: () => [{json:{escribieron:30,agendaron:10}}, {json:{escribieron:0,agendaron:0}}, {json:{escribieron:16,agendaron:1}}]});
assert.equal(totals[0].json.conversion, 23.91);
assert.throws(() => report({all: () => [{json:{escribieron:1,agendaron:2}}]}));
const classifier = new Function('$input', file('n8n_validar_clasificacion.js'));
assert.equal(classifier({all: () => [{json: {category:'agendar',confidence:0.95,needs_human:true}}]})[0].json.classification_valid,true);
assert.equal(classifier({all: () => [{json: {category:'agendar',confidence:'alta',needs_human:true}}]})[0].json.classification_valid,false);
const modelGuard = new Function('$input', file('n8n_validar_modelo.js'));
assert.equal(modelGuard({all: () => [{json: {category:'agendar', reason:'Pide cita', needs_human:true}}]})[0].json.classification_valid, true);
assert.equal(modelGuard({all: () => [{json: {category:'agendar', reason:'Pide cita', needs_human:false}}]})[0].json.classification_valid, false);
const zapApproval = new Function('inputData', file('zapier_aprobacion.js'));
assert.throws(() => zapApproval({estado:'APROBADO',revision:'',aprobada_revision:'',aprobado_por:'demo',payload_json:JSON.stringify(leads[0])}));
console.log('Pruebas de lógica JavaScript superadas. No son pruebas del editor de las plataformas.');
